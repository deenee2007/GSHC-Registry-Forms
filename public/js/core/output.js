  /* ── Appeals — Criminal and Civil Appeal Notice (Form 97, Order 43 Rule 2) ── */
  function appealNotice(d, u, r) {
    const isCriminal = r.formType === 'criminal-appeal-notice';
    const dd = splitDate(d.dateOfDecision), is = splitDate(d.issueDate);

    // Grounds wording differs between criminal and civil
    const groundsBody = isCriminal
      ? `That the decision of ${L(d.groundsDecisionBody)} is unreasonable, unwarranted and cannot be
         supported having regard to the evidence adduced before the court.`
      : `That the decision of ${L(d.groundsDecisionBody)} cannot be supported having regard to the
         weight of evidence adduced before the court.`;

    return shell(u,
      formRef('FORM 97 · ORDER 43 RULE 2') +
      title(isCriminal ? 'CRIMINAL APPEAL NOTICE OF APPEAL' : 'CIVIL APPEAL NOTICE OF APPEAL') +
      `<p>The Registrar,<br>${fmt(d.registrarAddress)}</p>
      <p>This is to give notice of appeal against the decision of the: ${L(d.decisionCourt)},
      details of which are as follows:</p>
      <p>1. Date of Decision: ${L(dd.day ? dd.day + ' ' + dd.month + ' 20' + dd.year2 : '')}
      &nbsp;&nbsp; ${L(d.appellant)} &mdash; Appellant</p>
      <p>2. Name of Parties:</p>` +
      parties(d.appellant, 'Appellant', d.respondent, 'Respondent') +
      `<p>3. Offence (in Criminal case) or Claim (in Civil matters):<br>
      ${fmt(d.offenceOrClaim)}</p>
      <p>4. Sentence (in Criminal cases) or Orders (in Civil matters):<br>
      ${fmt(d.sentenceOrOrders)}</p>` +
      `<div style="margin:14px 0"><strong>MY/OUR GROUNDS OF APPEAL ARE:</strong></div>` +
      `<p>${groundsBody}</p>
      <p>That more grounds will be filed on the receipt of record of proceeding.
      ${d.additionalGrounds ? '<br>' + fmt(d.additionalGrounds) : ''}</p>
      <p>DATE: ${dayLine(is)}.</p>
      <div class="doc-twosign">
        <div class="doc-sign">${fmt(d.respondentAddress)}<br>(RESPONDENT ADDRESS)</div>
        <div class="doc-sign">${esc(d.appellantPractitioner || '')}<br>(APPELLANT / LEGAL PRACTITIONER)</div>
      </div>`,
      r);
  }

  function generic(d, u, r, def) {
    const rows = (def && def.schema ? def.schema : []).filter(s => s.name)
      .map(s => `<div class="doc-kv"><strong>${esc(s.label)}:</strong> ${fmt(d[s.name])}</div>`).join("");
    return shell(u, title(def ? def.label : "FORM") + rows + sign("Registrar / Authorised Officer"), r);
  }

  // Render the formal document HTML for a record.
  function render(record, unitName, def) {
    const t = TEMPLATES[record.formType];
    return t ? t(record.data || {}, unitName, record) : generic(record.data || {}, unitName, record, def);
  }

  // Send a record to the printer via the dedicated print root.
  function print(record, unitName, def) {
    let root = document.getElementById("print-root");
    if (!root) { root = document.createElement("div"); root.id = "print-root"; document.body.appendChild(root); }
    root.innerHTML = render(record, unitName, def);
    document.body.classList.add("is-printing");
    window.print();
    setTimeout(() => { document.body.classList.remove("is-printing"); root.innerHTML = ""; }, 600);
  }

  window.App.output = { render, print, splitDate, formatDateTime };
