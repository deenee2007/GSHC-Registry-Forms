  function affidavitOfService(d, u, r) {
    const sv = splitDate(d.serviceDate), sw = splitDate(d.swornDate), pr = splitDate(d.processDate);
    const fem = d.personServedGender === "Female";
    const subj = fem ? "she" : "he", obj = fem ? "her" : "him";
    return shell(u,
      formRef(`IN THE ${esc((d.division || "GOMBE JUDICIAL DIVISION").toUpperCase())}<br>HOLDEN AT GOMBE`) +
      caseLine("Suit No.", d.suitNumber) +
      parties(d.plaintiff, "PLAINTIFF", d.defendant, "DEFENDANT") +
      title("AFFIDAVIT OF SERVICE") +
      `<p>I, ${L(d.bailiffName)}, Bailiff of this Honourable Court, make oath and say that ${onDayLine(sv)} at
       ${L(d.serviceTime, "short")} o'clock, I served upon ${L(d.servedUpon)}</p>
       <p>a ${L(d.processServed)} ${d.processSuitNumber ? "in Suit No. " + L(d.processSuitNumber) : ""}
       ${d.processDate ? "dated " + onDayLine(pr) : ""} being a true copy issued out of this Court at ${L(d.issuedAt)}.</p>
       ${d.complaintOf ? `<p>Upon the complaint/application of ${L(d.complaintOf)}.</p>` : ""}
       <p>By delivering the same personally to ${L(d.deliveredTo)} of ${L(d.recipientAddress, "long")} at
       ${L(d.placeOfService)}.</p>
       ${(d.unknownPerson || d.pointedOutBy || d.askedIdentity || d.identityResponse) ?
        `<p>Before the day I served the process, ${L(d.unknownPerson)} I did not know personally, but after
        ${subj} was pointed out to me by ${L(d.pointedOutBy)}, I asked ${obj} if ${subj} was ${L(d.askedIdentity)}
        and ${subj} said that ${subj} was ${L(d.identityResponse)}.</p>` : ""}` +
      sign("DEPONENT") +
      `<p>Sworn to at ${L(d.swornAt)} ${dayLine(sw)}.</p><div class="doc-beforeme">Before me</div>` +
      sign("Commissioner for Oaths"),
      r);
  }

