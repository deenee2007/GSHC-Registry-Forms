  /* ── Court Order Generator ── */
  function courtOrder(d, u, r) {
    const sd = splitDate(d.sittingDate), is = splitDate(d.issueDate);

    // Ordinal helper
    function ord(n) {
      const s = ['TH','ST','ND','RD'], v = n % 100;
      return n + (s[(v-20)%10] || s[v] || s[0]);
    }
    const DAYS  = ['SUNDAY','MONDAY','TUESDAY','WEDNESDAY','THURSDAY','FRIDAY','SATURDAY'];
    const MONTHS= ['JANUARY','FEBRUARY','MARCH','APRIL','MAY','JUNE',
                   'JULY','AUGUST','SEPTEMBER','OCTOBER','NOVEMBER','DECEMBER'];
    const sDate  = sd.day && sd.year4 ? new Date(d.sittingDate + 'T00:00:00') : null;
    const dayName= sDate ? DAYS[sDate.getDay()] : '';
    const ordDay = sd.day ? ord(parseInt(sd.day, 10)) : '';
    const mthName= sd.month ? (MONTHS[parseInt(sd.month,10)-1] || '') : '';
    const yr4    = sd.year4 || ('20' + (sd.year2 || ''));

    // Judge block
    const isPanel = d.judgeType === 'panel';
    let judgeLeft = '';
    let judgeFullLine = '';
    if (isPanel) {
      let pj = [];
      try { pj = Array.isArray(d.judges) ? d.judges : JSON.parse(d.judges || '[]'); } catch(e) {}
      judgeLeft = pj.filter(j=>j.name).map(j =>
        `<div class="co-judge-name">${esc(j.name)}</div>` +
        (j.designation ? `<div style="font-size:9pt">(${esc(j.designation)})</div>` : '')
      ).join('');
    } else {
      judgeLeft = `<div class="co-judge-name">${esc(d.judgeName||'')}</div>` +
        `<div style="font-size:9pt">(${esc(d.judgeDesignation||'JUDGE')})</div>`;
      judgeFullLine = `${esc(d.judgeName||'')} (${esc(d.judgeDesignation||'JUDGE')})`;
    }

    // Party labels
    const pMap = {
      'applicant-respondent': ['APPLICANTS','RESPONDENTS'],
      'plaintiff-defendant':  ['PLAINTIFF','DEFENDANT'],
      'appellant-respondent': ['APPELLANTS','RESPONDENTS']
    };
    const [leftRole, rightRole] = pMap[d.partyType] || ['APPLICANTS','RESPONDENTS'];

    // Process preamble
    const pTypeMap = {
      'motion-on-notice':   'MOTION ON NOTICE',
      'ex-parte':           'EX-PARTE MOTION',
      'writ-of-summons':    'WRIT OF SUMMONS',
      'originating-summons':'ORIGINATING SUMMONS',
      'chamber-summons':    'CHAMBER SUMMONS',
      'petition':           'PETITION',
      'other':              'APPLICATION'
    };
    const pLabel = pTypeMap[d.processType] || esc(d.processType || '');
    const pd = splitDate(d.processDate), fd = splitDate(d.filingDate);
    const pdStr = pd.day ? `${pd.day}/${pd.month}/${pd.year2}` : '';
    const fdStr = fd.day ? `${fd.day}/${fd.month}/${fd.year2}` : '';

    const preamble =
      `UPON ${pLabel} dated ${L(pdStr)} filed on the ${L(fdStr)}` +
      (d.applicableRules ? ` brought pursuant to ${fmt(d.applicableRules)}` : '') + `. ` +
      `The learned counsel ${L(d.counselName)} moved the motion praying on behalf of the ` +
      `${esc(d.onBehalfOf||'')} for ${fmt(d.prayer)}.` +
      (d.furtherNarrative ? `<br><br>${fmt(d.furtherNarrative)}` : '');

    // Order items
    let items = [];
    try { items = Array.isArray(d.orderItems) ? d.orderItems : JSON.parse(d.orderItems||'[]'); } catch(e){}
    const itemsHtml = items.length
      ? `<ol>${items.map(it => `<li>${fmt(it.item)}</li>`).join('')}</ol>`
      : `<ol><li>${L('')}</li></ol>`;

    // Additional suits
    const addSuits = d.additionalSuits
      ? d.additionalSuits.split('\n').filter(Boolean)
          .map(s => `<p style="text-align:right;font-weight:700">${esc(s.trim())}</p>`).join('')
      : '';

    // Closing line
    const closingJudge = isPanel
      ? 'THE PANEL OF JUSTICES'
      : (judgeFullLine ? judgeFullLine + ' ' : 'THE HONOURABLE JUDGE ');
    const closingDate = is.day
      ? `${ord(parseInt(is.day,10))} DAY OF ${MONTHS[parseInt(is.month,10)-1]||''} ${is.year4||'20'+(is.year2||'')}`
      : '_____ DAY OF _____________ 20____';

    return shell(u,
      formRef(`IN THE GOMBE JUDICIAL DIVISION<br>HOLDEN AT GOMBE`) +
      `<div style="text-align:center;font-weight:700;font-size:11pt;margin:4px 0">` +
        `ON ${dayName} THE ${ordDay} DAY OF ${mthName}, ${yr4}</div>` +
      `<div style="text-align:center;font-size:11pt;margin:2px 0">` +
        (isPanel ? `<strong>BEFORE THEIR LORDSHIPS:</strong>` : `<strong>BEFORE HIS LORDSHIP: ${esc(d.judgeName||'')}</strong>`) +
      `</div>` +
      `<div style="text-align:right;font-weight:700;margin:8px 0">SUIT NO. ${esc(d.suitNumber||'')}</div>` +
      addSuits +
      `<div class="co-parties">
        <p><strong>BETWEEN:</strong></p>
        <div class="co-party-row">
          <div class="co-party-names">${fmt(d.leftParties)}</div>
          <div class="co-party-role">${leftRole}</div>
        </div>
        <p style="text-align:center"><strong>AND</strong></p>
        <div class="co-party-row">
          <div class="co-party-names">${fmt(d.rightParties)}</div>
          <div class="co-party-role">${rightRole}</div>
        </div>
      </div>` +
      `<table class="co-table">
        <tr>
          <td class="co-left-col"></td>
          <td class="co-right-col">
            <div class="co-order-title">${esc(d.orderHeading||'COURT ORDER')}</div>
            <p class="co-preamble">${preamble}</p>
          </td>
        </tr>
        <tr>
          <td class="co-left-col" style="vertical-align:top;padding-top:4px;">${judgeLeft}</td>
          <td class="co-right-col">
            <div class="co-it-is-ordered">IT IS HEREBY ORDERED THAT;</div>
            <div class="co-items">${itemsHtml}</div>
          </td>
        </tr>
        <tr>
          <td class="co-left-col" style="vertical-align:top;">
            <div class="co-seal-space"></div>
          </td>
          <td class="co-right-col"></td>
        </tr>
      </table>` +
      `<div class="co-closing">THE ORDER IS GIVEN UNDER THE HAND AND SEAL OF ${closingJudge}<br>
        DATED THE ${closingDate}.</div>` +
      `<div class="doc-sign-wrap"><div class="doc-sign">${esc(d.registrarName||'')}<br>(${esc(d.registrarDesignation||'')})</div></div>`,
      r);
  }

